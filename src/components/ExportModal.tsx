"use client";

import React, { useState } from "react";
import { ContractAuditResult } from "@/lib/types";
import { X, Copy, Download, Printer, Check, FileCheck } from "lucide-react";

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  audit: ContractAuditResult;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  audit,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const markdownContent = `# ClauseGuard Contract Risk Audit Report
**Document**: ${audit.contractTitle}  
**Classification**: ${audit.contractType}  
**Overall Risk Score**: ${audit.overallRiskScore}/100  
**Audit Date**: ${new Date(audit.analyzedAt || Date.now()).toLocaleDateString()}  
**Engine**: ${audit.modelUsed || "Gemini Flash"}

---

## 1. Executive Summary
${audit.summary}

---

## 2. Top Dealbreakers
${audit.dealbreakers.map((d) => `- ⚠️ **${d}**`).join("\n")}

---

## 3. Category Risk Exposure
${audit.categoryScores
  .map(
    (c) =>
      `- **${c.name}**: ${c.score}/100 (${c.flagCount} flags, ${c.criticalCount} critical)`
  )
  .join("\n")}

---

## 4. Flagged Clauses & Redline Amendments

${audit.flaggedClauses
  .map(
    (fc, idx) => `### ${idx + 1}. [${fc.severity}] ${fc.title} (${fc.category})

**Original Contract Language:**
> "${fc.originalText}"

**Plain-English Breakdown:**  
${fc.plainEnglishExplanation}

**Identified Risk / Trap:**  
${fc.trapAnalysis}

**Recommended Counter-Amendment (Redline):**
\`\`\`text
${fc.recommendedRedline}
\`\`\`

**Negotiation Tip:**  
*${fc.negotiationTip}*
`
  )
  .join("\n---\n\n")}

---

## 5. Counter-Offer Email Draft
\`\`\`text
${audit.negotiationEmailDraft}
\`\`\`

---
*Generated by ClauseGuard AI using Google Gemini Flash. This report constitutes risk evaluation, not formal attorney-client legal representation.*
`;

  const handleCopy = () => {
    navigator.clipboard.writeText(markdownContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const blob = new Blob([markdownContent], { type: "text/markdown;charset=utf-8;" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `ClauseGuard-Audit-${audit.contractTitle.replace(/[^a-z0-9]/gi, "_").toLowerCase()}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm">
      <div className="bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 rounded-2xl w-full max-w-3xl shadow-2xl overflow-hidden flex flex-col max-h-[85vh]">
        {/* Header */}
        <div className="px-6 py-4 border-b border-slate-100 dark:border-slate-800 flex items-center justify-between">
          <div className="flex items-center space-x-2">
            <FileCheck className="w-5 h-5 text-indigo-600 dark:text-indigo-400" />
            <h3 className="font-bold text-base text-slate-900 dark:text-white">
              Export Audit Report
            </h3>
          </div>
          <button
            onClick={onClose}
            className="p-1 rounded-lg text-slate-400 hover:text-slate-600 dark:hover:text-slate-200"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content Preview */}
        <div className="flex-1 overflow-y-auto p-6 bg-slate-50 dark:bg-slate-950">
          <pre className="text-xs font-mono text-slate-800 dark:text-slate-200 whitespace-pre-wrap leading-relaxed select-text">
            {markdownContent}
          </pre>
        </div>

        {/* Footer Actions */}
        <div className="px-6 py-4 border-t border-slate-100 dark:border-slate-800 bg-white dark:bg-slate-900 flex flex-wrap items-center justify-between gap-3">
          <button
            onClick={handlePrint}
            className="inline-flex items-center space-x-1.5 px-3.5 py-2 rounded-xl border border-slate-200 dark:border-slate-700 text-xs font-medium text-slate-700 dark:text-slate-300 hover:bg-slate-50 dark:hover:bg-slate-800 transition"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>Print / Save PDF</span>
          </button>

          <div className="flex items-center space-x-2">
            <button
              onClick={handleCopy}
              className="inline-flex items-center space-x-1.5 px-4 py-2 rounded-xl border border-slate-200 dark:border-slate-700 text-xs font-medium text-slate-700 dark:text-slate-300 hover:bg-slate-50 dark:hover:bg-slate-800 transition"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-500" />
                  <span>Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5" />
                  <span>Copy Markdown</span>
                </>
              )}
            </button>

            <button
              onClick={handleDownload}
              className="inline-flex items-center space-x-1.5 px-4 py-2 rounded-xl bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-medium transition shadow-sm"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download (.md)</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
